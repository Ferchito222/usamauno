    <center><strong>CAPITAL ADICIONAL INDEMNIZATORIO POR DESEMPLEO</strong></center>
    <br>
    <strong>FORMA PARTE DE: PÓLIZA DE SEGURO DE DESGRAVAMEN</strong>
    <br>
    Mediante la presente cobertura adicional, queda entendido y acordado que, en virtud al 
    pago de la correspondiente prima adicional, la presente póliza se extiende a cubrir un Capital Adicional 
    Indemnizatorio por Desempleo, de acuerdo a los términos y/o condiciones que se estipulan a continuación.
    <br>
    <strong>Art. 1. DEFINICIONES</strong>
    <br>
    <strong>Contratante o Tomador:</strong>  Empresa jurídica o de intermediación Financiera que por cuenta y a nombre del Asegurado, contrata con la Entidad Aseguradora el Seguro.
    <br>
    <strong>Compañía:</strong> Entidad aseguradora legalmente establecida en Bolivia debidamente registrada y autorizada por la Autoridad 
    de Fiscalización y Control de Pensiones y Seguros (APS), constituida con Matricula de Comercio No. 00101377, NIT No. 297860029, 
    con razón social <strong>Compañía de Seguros de Vida Fortaleza S.A.</strong>
    <br>
    <strong>Asegurado:</strong>  La persona natural o jurídica titular del interés amparado por el seguro.
    <br>
    <strong>Beneficiario:</strong> Es la persona designada por el asegurado como habilitada para recibir total o parcialmente el beneficio de la indemnización en caso de siniestro.  El tomador del seguro puede ser designado como beneficiario, previo consentimiento del asegurado.
    <br>
    <strong>Carencia:</strong> Tiempo contado desde la iniciación de la vigencia del amparo otorgado por la póliza, durante el cual el ASEGURADO no tiene derecho a reclamar el presente beneficio.
    <br>
    <strong>Normativa Laboral:</strong> Normativa vigente bajo la cual se determinan los derechos y obligaciones emergentes del trabajo, tales como la Ley General del Trabajo del 8 de diciembre de 1942, su Decreto Reglamentario (DS 224 de 24 de julio de 1943) y demás disposiciones legales conexas vigentes en el Estado Plurinacional de Bolivia.
    <br>
    <strong>Prima:</strong> Es el valor determinado por LA COMPAÑÍA, como contraprestación por la cobertura de seguro contratada.
    <br>
    <strong>Trabajador Dependiente:</strong> Persona natural que trabaja por cuenta ajena ya sea como empleado u 
    obrero y que mantiene un contrato laboral ya sea verbal o escrito (según Titulo II, Capítulo I Disposiciones 
    generales, art. 6 de la Ley General del Trabajo) por tiempo indefinido o contrato a plazo fijo por el plazo de 
    máximo un año, de acuerdo a lo establecido en el artículo 2 de la Ley General del Trabajo. (Art.2. – Patrono y/o Empleador es 
    la persona natural o jurídica que proporciona trabajo por cuenta propia o ajena, para la ejecución o explotación de una 
    obra o empresa. Empleado y obrero es el que trabaja por cuenta ajena. Se distingue el primero por prestar servicios 
    en tal carácter; o por trabajar en oficina con horario y condiciones especiales, desarrollando un esfuerzo predominantemente 
    intelectual. Quedan comprendidos en esta categoría de empleados; todos los trabajadores favorecidos por leyes especiales. 
    Se caracteriza el obrero por prestar servicios de índole material o manual, comprendiéndose en esta categoría, también, 
    al que prepara o vigila el trabajo de otros obreros, tales como capataces y vigilantes).
    <br>
    <strong>Trabajador Dependiente:</strong>
    <br>
    Podrá ingresar como ASEGURADO bajo la presente Póliza, cualquier persona que haya cumplido dieciocho (18) años 
    y que no supere la edad máxima de ingreso de sesenta y cinco (65) años y 364 días (a la fecha de presentación 
    de su Certificado de Cobertura) establecida en las Condiciones Particulares, pudiendo permanecer como ASEGURADO 
    sólo hasta la edad máxima de permanencia de 70 años y 364 días.
    <br>
    EL TOMADOR y/o el ASEGURADO deberán probar mediante documentación fehaciente, la fecha de nacimiento del ASEGURADO 
    declarada para obtener la cobertura, dicha prueba podrá ser presentada por el ASEGURADO en cualquier momento. 
    Asimismo, LA COMPAÑÍA podrá exigirla antes de otorgar cualquier beneficio acordado por la Póliza
    <br>
    La Cobertura Individual será declarada nula cuando el seguro haya sido suscrito para una persona menor a diez y ocho (18) años.
    <br>
    <strong>Art. 3. PRIMAS</strong>
    <br>
    Según lo establecido para las coberturas básicas en el condicionado particular y general de la póliza.
    <br>
    <strong>Art. 4. BENEFICIARIO DEL SEGURO</strong>
    <br>
    Se considera como Beneficiario de la Cobertura de desempleo involuntario al Tomador.
    <br>
    <strong>Art. 5. COBERTURA</strong>
    <br>
    Mediante el presente anexo éste seguro cubre el pago de (6)  cuotas mensuales del crédito de capital e 
    intereses corrientes, de los Asegurados que sean empleados y figuren en la planilla de personal de una 
    empresa legalmente establecida en Bolivia, con relación laboral indefinida con un  vínculo laboral mediante 
    contrato verbal o escrito de trabajo visado por el Ministerio de Trabajo, Empleo y Previsión Social con 
    dependencia con más de seis (6) meses de antigüedad continua, que por razones involuntarias hayan perdido su 
    empleo, por despido intempestivo sin justa causa, cierre temporal o definitivo de la empresa o supresión de 
    cargos por fusión, transformación o liquidación de empresas privadas. Por tanto, no cubre el desempleo por 
    finalización del contrato en el plazo acordado en el mismo, si el empleador decide rescindir unilateralmente 
    el contrato a plazo fijo de forma anticipada, el asegurado podrá activar la cobertura.
    <br>
    Queda claramente establecido que el límite máximo a indemnizar por cada cuota, será el monto establecido en el 
    plan de pagos a la fecha del despido involuntario, en su defecto el promedio de las últimas tres cuotas pagadas por 
    el asegurado, siempre que no haya sido contratado por otra empresa y una vez cumplido el periodo de eliminación 
    (carencia) de tres (3) meses desde la contratación de la presente cobertura.
    <br>
    <strong>Art. 6. CONDICIONES DE ASEGURABILIDAD </strong>
    <br>
    El ASEGURADO para obtener la cobertura descrita en el presente anexo, deberá cumplir con las siguientes condiciones:
    <br>
    <ul type="a">
        <li>No haber superado la edad máxima de permanencia definida en las Condiciones Particulares de la presente póliza.</li>
        <li>Tener un Contrato de trabajo por Tiempo Indefinido o a Plazo Fijo de máximo un (1) año.</li>
        <li>Tener una antigüedad en su trabajo superior a los seis (6) meses al momento de contratar la presente cobertura.</li>
        <li>Estar bajo el amparo de la Ley General del Trabajo, su Decreto Reglamentario y demás disposiciones complementarias.</li>
    </ul>
    <strong>Art. 7. EXCLUSIONES Y RIESGOS NO CUBIERTOS</strong>
    <br>
    Se excluyen de la presente cobertura:
    <br>
    <ul type="a">
        <li>Pérdida del empleo para trabajadores con una antigüedad menor a seis (6) meses con el mismo empleador.</li>
        <li>Se excluye los retiros voluntarios o los retiros pactados entre empleado y empleador que no impliquen indemnización por parte del empleador y no hubo conciliación ante Autoridad competente.</li>
        <li>Participar en paros, disputas laborales o huelgas que sean declaradas ilegales por las Autoridades Competentes.</li>
        <li>Despido por infracción de cualquiera de los incisos del Art. 16 de la Ley General del Trabajo y/o 
            de su Decreto Reglamentario.
            <br>
            <strong>- Ley Gral. Del Trabajo Art. 16°</strong> No habrá lugar a desahucio ni indemnización cuando exista una de las 
            siguientes causales:
            <br>
            a) Perjuicio material causado con intención en los instrumentos de trabajo;<br>
            b) Revelación de secretos industriales;<br>
            c) Omisiones o imprudencias que afecten a la seguridad o higiene industrial;<br>
            d) Incumplimiento total o parcial del convenio;<br>
            e) Robo o hurto por el trabajador.<br>
            <strong>- Decreto Reglamentario 224. Art. 9º</strong> No habrá lugar a desahucio ni indemnización cuando exista una de las siguientes causales:
            <br>
            a) Perjuicio material causado con intención en las máquinas, productos o mercaderías;<br>
            b) Revelación de secretos industriales:<br>
            c) Omisiones e imprudencias que afecten a la higiene y seguridad industriales;<br>
            d) Inasistencia injustificada de más de tres días consecutivos o de más de seis en el curso de un mes;<br>
            e) Incumplimiento total o parcial del contrato de trabajo o del reglamento interno de la empresa;<br>
            f) Retiro voluntario del trabajador, antes de los términos fijados en el artículo 13 de la ley o en el del contrato;<br>
            g) Abuso de confianza, robo o hurto por el trabajador;<br>
            h) Vías de hecho, injurias o conducta inmoral en el trabajo;<br>
            Abandono en masa del trabajo, siempre que los trabajadores no obedecieran a la intimación de la autoridad competente.
        </li>
        <li>Desempleo originado por discapacidad mental del ASEGURADO, determinado por el Instituto Nacional de Salud Ocupacional INSO o la Entidad Encargada de Calificar EEC.</li>
        <li>Pérdida del empleo del ASEGURADO, notificada por el empleador previo a la fecha de inicio de la vigencia de la póliza o del Certificado de Cobertura.</li>
        <li>Terminación del contrato por vencimiento del término acordado, cuando éste sea a plazo fijo, temporal, eventual, de obra o servicio.</li>
        <li>No cubre ni alcanza a trabajadores dependientes en período de prueba.</li>
        <li>Cuando el ASEGURADO mantenga vigente otro vínculo laboral en forma simultánea que sea demostrable mediante contrato laboral vigente o cualquier otro mecanismo de prueba.</li>
        <li>Se excluye a las personas que trabajen en forma independiente.</li>
        <li>Desempleo involuntario del ASEGURADO que se inicie dentro del período de carencia.</li>
        <li>Fallecimiento del ASEGURADO.</li>
        <li>Jubilación del ASEGURADO.</li>
        <li>Suspensiones laborales temporales por vacaciones, estudios, maternidad, épocas de paro cíclicas y las dispuestas por la Autoridad Competente.</li>
        <li>Fraude al seguro o su intento.</li>
        <li>Dolo o mala fe por parte del Asegurado y/o Tomador del seguro.</li>
    </ul>
    <strong>Art. 8. EFECTO Y TERMINACIÓN</strong>
    <br>
    El presente Anexo toma efecto al momento de la solicitud de seguro por parte del Asegurado y concluye 
    automáticamente bajo una de las siguientes causas:
    <br>
    <ul type="a">
        <li>Al terminarse la póliza principal por cualquier motivo, </li>    
        <li>Al suspenderse el pago de primas, </li>    
        <li>Al cumplir la edad máxima el Asegurado estipulada en las Condiciones Particulares,</li>
        <li>Al activarse la cobertura de invalidez total y permanente,</li>
        <li>Al finalizar la vigencia de la póliza principal,</li>
        <li>Cuando se hubiera presentado documentación o información adulterada, fraudulenta o inexacta para acceder 
            a alguno de los beneficios del seguro. La reticencia o inexactitud en las declaraciones del ASEGURADO, 
            sin dolo de su parte, dan derecho a LA COMPAÑÍA a demandar la anulación del contrato dentro de los treinta 
            (30) días de conocidos tales hechos por él, debiendo restituir, en este caso, las primas del periodo no 
            corrido. Pasado este plazo, no puede impugnar el contrato por las causas señaladas. Si se subsanan los errores 
            u omisiones puede optar por reajustar las primas de acuerdo al verdadero estado de riesgo. Las declaraciones 
            falsas o reticentes hechas con dolo o mala fe hacen nulo el contrato de seguro. En este caso el ASEGURADO 
            no tendrá derecho a la devolución de las primas pagadas, Este párrafo se rige conforme a los artículos 
            994 y 999 del Código de Comercio.</li>
        <li>Cuando el ASEGURADO cambie de condición de Empleado Dependiente a Empleado Independiente.</li>
    </ul> 
    <strong>Art. 9. PROCEDIMIENTO PARA INDEMNIZACIÓN:</strong>
    <br>
    Producido el siniestro el Asegurado tendrá un plazo de quince (15) días calendario para avisar al 
    Contratante o Tomador del seguro y/o la Aseguradora sobre el hecho, salvo fuerza mayor o impedimento 
    justificado, a su vez el Contratante o Tomador del seguro tendrá un plazo de quince (15) días calendarios 
    desde conocido el siniestro para dar aviso a la Aseguradora.
    <br>
    Para solicitar la indemnización del seguro el interesado, en su caso a través del Tomador o 
    Contratante, deberá enviar a la Aseguradora mediante nota expresa los siguientes documentos y respaldos:
    <br>
    <ul>
        <li>Nota de aviso de siniestro firmada por el Asegurado,</li>
        <li>Original y Copia del Formulario de Finiquito visado por el Ministerio de Trabajo, firmado por el 
            Empleador, el ASEGURADO y un representante del Ministerio de Trabajo (el original se devolverá al ASEGURADO una vez verificados los documentos).</li>
        <li>Copia de la cédula de identidad del asegurado,
            Nota, memorándum o documento de despido o conclusión anticipada laboral, en original o copia legalizada, que detalle las causas del despido o conclusión anticipada laboral. (el original se devolverá al ASEGURADO una vez verificados los documentos).</li>
        <li>Plan de pagos actualizado a la fecha del siniestro y/o extracto del préstamo.</li>
        <li>Extracto de AFP (A partir de la segunda cuota)</li>
        <li>En su caso la Compañía podrá requerir información adicional para comprobar la ocurrencia del siniestro.</li>
    </ul>
    LA COMPAÑÍA debe pronunciarse sobre el derecho del ASEGURADO dentro de los treinta (30) días de recibidos todos los informes, 
    evidencias, documentos y/o requerimientos adicionales acerca de los hechos y circunstancias del siniestro, las evidencias 
    conducentes a la determinación de la causa, identidad de las personas o intereses asegurados y cuantía de los daños, de 
    acuerdo a lo establecido en el Artículo 1031 del Código de Comercio, se dejará constancia escrita de la fecha de recepción 
    de la información y evidencias a efectos del cómputo del plazo. El plazo de treinta (30) días mencionado, fenece con la 
    aceptación o rechazo del siniestro o con la solicitud de LA COMPAÑÍA a EL ASEGURADO/TOMADOR que se complementen los requerimientos 
    contemplados en el artículo 1031 y no vuelve a correr hasta que el ASEGURADO haya cumplido con tales requerimientos. 
    La solicitud de complementos establecidos en el Artículo 1031 por parte de LA COMPAÑÍA no podrá extenderse por más de 
    dos veces a partir de la primera solicitud de informes y evidencias, debiendo pronunciarse dentro del plazo establecido 
    y de manera definitiva sobre el derecho de EL ASEGURADO, después de la entrega por parte de EL ASEGURADO del último 
    requerimiento de información.  En caso de demora u omisión del ASEGURADO en proporcionar la información y evidencias 
    sobre el siniestro, el término señalado no corre hasta el cumplimiento de estas obligaciones. El silencio de LA COMPAÑÍA, 
    vencido el término para pronunciarse, importa la aceptación del reclamo.
    <br>
    LA COMPAÑÍA procederá al pago en efectivo del Beneficio en el plazo máximo de quince (15) días calendario de haberse dado el 
    aviso de pronunciamiento de pago, en la moneda definida en el Condicionado Particular, de conformidad a los dispuesto por el 
    Código de Comercio en su artículo 1025.
    <br>
    Corresponderá a EL TOMADOR, solicitar al ASEGURADO los documentos indicados para acceder al beneficio respectivo.
    <br>
    En los casos en los que exista un procedimiento judicial, administrativo o arbitral en el que no sea parte 
    LA COMPAÑÍA y de cuya definición dependa la cobertura del siniestro o el derecho del ASEGURADO, LA COMPAÑÍA podrá supeditar 
    la decisión de la cobertura del siniestro o el pago del beneficio a la conclusión en última instancia del proceso respectivo.  
    <br>
    <strong>Art. 10. CONDICION ESPECIAL PARA REPROGRAMACIONES Y REFINANCIAMIENTOS</strong>
    <br>
    Los Créditos que sean reprogramados/refinanciados durante la vigencia del mismo, que mantengan el número de operación 
    con el que fue desembolsado, no perderán la antigüedad adquirida desde la contratación de la presente cobertura.
    <br>
    Los créditos que sean refinanciados durante la vigencia del mismo, que no mantengan el número de operación con el que fue 
    desembolsado, perderán la antigüedad adquirida desde la contratación de la presente cobertura.
    <br>
    Todos los demás términos y condiciones de la Póliza de la cual el presente anexo forma parte integrante e indivisible se 
    mantienen sin alteración.

